import math

import numpy as np
import pytest

from opendbc.car.vehicle_model import VehicleModel
from openpilot.sunnypilot.selfdrive.controls.lib.honda_eps.geometry import InsightRackMap, curvature_from_angle, desired_angle_no_offset


@pytest.mark.parametrize("speed,curvature,roll,expected", [
  (0, .001, 0, -2.7629170796798563),
  (3, .01, 0, -27.24426918588717),
  (10, .005, 0, -14.458135176313043),
  (20, .001, 0, -3.4923271887153375),
  (30, .001, 0, -4.392087000107667),
  (10, .005, .04, -13.76646985216098),
  (10, -.005, .04, 15.148098674436186),
  (10, 0, .04, .7155513169638079),
])
def test_pinned_james_rack_output(speed, curvature, roll, expected):
  # Generated by the unmodified HondaEpsRackMap in James bfcbbf24, using its
  # Insight A table and a 2.7 m wheelbase. Includes both turn and roll signs.
  assert InsightRackMap(2.7).angle_from_curvature(curvature, speed, roll) == pytest.approx(expected, abs=1e-12)


def test_geometry_leaves_vehicle_model_and_mvl_conversion_intact(car_factory):
  CP, _ = car_factory()
  vm = VehicleModel(CP)
  before = vars(vm).copy()
  for speed in (0, 3, 10, 20, 30):
    for curvature in (-.005, 0, .005):
      for roll in (-.04, 0, .04):
        angle = desired_angle_no_offset(vm, speed, roll, curvature)
        assert angle == math.degrees(vm.get_steer_from_curvature(-curvature, speed, roll))
        assert curvature_from_angle(vm, speed, roll, angle) == pytest.approx(curvature, abs=1e-12)
        assert math.isfinite(desired_angle_no_offset(vm, speed, roll, curvature, "james"))
        angle = desired_angle_no_offset(vm, speed, roll, curvature, "james")
        assert curvature_from_angle(vm, speed, roll, angle, "james") == pytest.approx(curvature, abs=1e-12)
  assert vars(vm) == before


def test_rack_roundtrip_and_monotonicity():
  rack = InsightRackMap(2.7)
  for speed in (0, 3, 10, 20, 35):
    for roll in (-.1, 0, .1):
      angles = np.linspace(-400, 400, 101)
      curvatures = [rack.curvature_from_angle(angle, speed, roll) for angle in angles]
      assert np.all(np.diff(curvatures) < 0)
      for angle, curvature in zip(angles, curvatures, strict=True):
        assert rack.angle_from_curvature(curvature, speed, roll) == pytest.approx(angle, abs=1e-9)


@pytest.mark.parametrize("value", [math.nan, math.inf, -math.inf])
@pytest.mark.parametrize("index", [0, 1, 2])
def test_geometry_rejects_nonfinite_inputs(car_factory, value, index):
  CP, _ = car_factory()
  inputs = [10., .0, .001]
  inputs[index] = value
  speed, roll, curvature = inputs
  for mode in ("mvl", "james"):
    with pytest.raises(ValueError):
      desired_angle_no_offset(VehicleModel(CP), speed, roll, curvature, mode)


def test_geometry_rejects_unknown_mode_and_invalid_dimensions(car_factory):
  CP, _ = car_factory()
  with pytest.raises(ValueError):
    desired_angle_no_offset(VehicleModel(CP), 10, 0, .001, "unrecognized")
  assert desired_angle_no_offset(VehicleModel(CP), -1, 0, .001) == desired_angle_no_offset(VehicleModel(CP), 0, 0, .001)
  for wheelbase in (0, -1, math.nan, math.inf):
    with pytest.raises(ValueError):
      InsightRackMap(wheelbase)
