"""One bounded compute subprocess; only fixed compiler/export/diagnostic entrypoints."""
import argparse
import importlib.abc
import hashlib
import json
import os
from pathlib import Path
import resource
import runpy
import sys


def verify_warp(arguments, identity, source_identity):
  """Fresh-buffer source/disk-reload checks for our locally compiled camera warp."""
  import numpy as np
  from examples.openpilot.compile_warp import make_frame_prepare, parse_frame, parse_size
  from tinygrad import Device, Tensor
  from openpilot.sunnypilot.modeld_v2.helpers import load_model
  from tools.navigation_hardware.safety import sha256

  def option(name):
    return arguments[arguments.index(name) + 1]
  output = Path(option('--output'))
  report = {'scope': 'warp_source_reload_consistency_only', 'status': 'running', 'artifact_sha256': sha256(output),
            'source_commit': source_identity['commit'], 'tinygrad_ref': source_identity['tinygrad_ref'], 'device': identity,
            'seeds': [42, 43], 'runs': [], 'hardware_driving_validation': False}
  report_path = output.with_name(output.name + '.verification.json')
  try:
    # These extras were generated by the local warp compiler and contain no public model metadata.
    loaded = load_model(str(output), verify=True, cache=False)
    frame = parse_frame(option('--frame'))
    warp = make_frame_prepare(frame, *parse_size(option('--warp-to')))
    previous = None
    for seed in report['seeds']:
      rng = np.random.default_rng(seed)
      pixels = rng.integers(0, 256, (2, frame.size), dtype=np.uint8)
      matrices = np.broadcast_to(np.eye(3, dtype=np.float32), (2, 3, 3)).copy()
      matrices[:, :2, 2] = rng.uniform(0, 5, (2, 2))
      source_images = Tensor(pixels.copy(), device=Device.DEFAULT).realize()
      source_matrices = Tensor(matrices.copy(), device=Device.DEFAULT).realize()
      expected = Tensor.stack(*(warp(source_images[index], source_matrices[index]) for index in range(2))).numpy().copy()
      actual = loaded['run'](input_frame=Tensor(pixels.copy(), device=Device.DEFAULT).realize(),
                             M_inv=Tensor(matrices.copy(), device=Device.DEFAULT).realize()).numpy().copy()
      if expected.shape != (2, 6, 128, 256) or actual.shape != expected.shape or expected.dtype != np.uint8 or actual.dtype != np.uint8:
        raise ValueError('Warp source/reload shape or dtype mismatch')
      if not np.array_equal(expected, actual):
        raise ValueError('Warp source/reload uint8 images differ')
      digest = hashlib.sha256(expected.tobytes()).hexdigest()
      report['runs'].append({'seed': seed, 'exact_uint8_match': True, 'output_sha256': digest})
      if previous == digest:
        raise ValueError('Independent warp inputs produced identical outputs; exclude no-op execution')
      previous = digest
    report['status'] = 'passed_source_reload_consistency'
  except BaseException as error:
    report.update(status='failed', error=f'{type(error).__name__}: {error}')
    raise
  finally:
    report_path.write_text(json.dumps(report, indent=2) + '\n')


class NoPersistentFlash(importlib.abc.MetaPathFinder):
  def find_spec(self, fullname, path=None, target=None):
    if fullname.startswith(('openpilot.system.hardware.chestnut.flash', 'openpilot.system.hardware.hardwared',
                            'system.hardware.chestnut.flash', 'system.hardware.hardwared')):
      raise RuntimeError('Persistent firmware/production hardware daemon imports are forbidden in hardware diagnostics')
    return None


def admitted_device(device):
  identity = {'architecture': device.arch, 'interface': type(device.iface).__name__, 'usb': bool(device.is_usb),
              'renderer_target': vars(device.renderer.target)}
  if device.arch != 'gfx1200' or device.is_usb is not True or type(device.iface).__name__ != 'USBIface':
    raise ValueError(f'Actual discovered GPU/USB target is unsupported: {identity}')
  target = identity['renderer_target']
  if target.get('device') != 'AMD' or target.get('renderer') != 'LLVM' or target.get('arch') != device.arch or target.get('interface') != 'USB':
    raise ValueError('Actual renderer target must be AMD LLVM gfx1200 USB')
  return identity


def main():
  parser = argparse.ArgumentParser(description=__doc__)
  parser.add_argument('--stage', choices=('compile', 'warp', 'export', 'diagnostic'), required=True)
  parser.add_argument('--backend', choices=('AMD', 'CPU'), required=True)
  parser.add_argument('--checkout', type=Path, required=True)
  parser.add_argument('--identity-output', type=Path, required=True)
  parser.add_argument('arguments', nargs=argparse.REMAINDER)
  args = parser.parse_args()
  if os.environ.get('NAV_HARDWARE_NON_ACTUATING') != '1':
    parser.error('This worker must be launched by the admitted non-actuating hardware package')
  if any(os.environ.get(key, '0') not in ('', '0') for key in ('MOCKGPU', 'MOCKKFD', 'MOCKUSB', 'ASM_CALL', 'NO_HIPCC')):
    parser.error('Emulated/no-op backends are not accepted')
  from tools.navigation_hardware.safety import preflight
  admission = preflight(args.checkout, args.identity_output.parent)
  if not admission['admitted']:
    parser.error('; '.join(admission['errors']))
  resource.setrlimit(resource.RLIMIT_CORE, (0, 0))
  sys.meta_path.insert(0, NoPersistentFlash())
  identity = {'backend': args.backend, 'persistent_firmware_operations': False}
  if args.backend == 'AMD':
    if os.environ.get('DEV') != 'USB+AMD:LLVM':
      parser.error('Discover physical USB architecture with DEV=USB+AMD:LLVM; do not force an architecture')
    from tinygrad import Device
    identity.update(admitted_device(Device['AMD']))
  args.identity_output.write_text(json.dumps(identity, indent=2) + '\n')
  scripts = {'compile': 'openpilot/sunnypilot/modeld_v2/compile_modeld_v2.py',
             'warp': 'openpilot/sunnypilot/modeld_v2/compile_warp.py',
             'export': 'openpilot/selfdrive/navigation/export_experimental_model.py', 'diagnostic': 'tools/navigation_model_diagnostic.py'}
  arguments = args.arguments[1:] if args.arguments[:1] == ['--'] else args.arguments
  sys.argv = [str(args.checkout / scripts[args.stage]), *arguments]
  runpy.run_path(sys.argv[0], run_name='__main__')
  if args.stage == 'warp':
    verify_warp(arguments, identity, admission['source'])


if __name__ == '__main__':
  main()
